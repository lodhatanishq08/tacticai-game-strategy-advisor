import React, { useState, useEffect } from 'react';
import { runAnalysis, fetchFormations } from '../utils/api';
import { Section, FormationPitch, WeaknessCard, ConfidenceBar, AgentPipeline, InfoTag } from '../components/ui';

export default function StrategyPage({ selectedTeam, teams }) {
  const [selectedOpponent, setSelectedOpponent] = useState('');
  const [result, setResult] = useState(null);
  const [loading, setLoading] = useState(false);
  const [formations, setFormations] = useState(null);
  const [activeTab, setActiveTab] = useState('overview');

  const opponents = teams.filter(t => t.id !== selectedTeam);

  useEffect(() => {
    if (opponents.length > 0 && !selectedOpponent) setSelectedOpponent(opponents[0].id);
  }, [teams, selectedTeam]);

  useEffect(() => {
    fetchFormations().then(d => setFormations(d.formations)).catch(() => {});
  }, []);

  const handleGenerate = async () => {
    if (!selectedOpponent) return;
    setLoading(true);
    setResult(null);
    try {
      const r = await runAnalysis(selectedTeam, selectedOpponent);
      setResult(r);
      setActiveTab('overview');
    } finally {
      setLoading(false);
    }
  };

  const team = teams.find(t => t.id === selectedTeam);
  const opponent = teams.find(t => t.id === selectedOpponent);
  const rec = result?.agents?.strategyRecommendation?.recommendation;
  const explanation = result?.agents?.insightExplanation;
  const summary = result?.summary;

  const tabs = ['overview', 'attacking', 'defending', 'players', 'alternatives', 'coaching'];

  return (
    <div>
      <div className="page-header">
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
          <div>
            <h1 style={{ fontSize: '22px', fontWeight: 800, margin: 0 }}>Strategy Advisor</h1>
            <div style={{ color: 'var(--text-muted)', fontSize: '13px', marginTop: 2 }}>AI-powered tactical game plan generation</div>
          </div>
          <div style={{ display: 'flex', gap: 12 }}>
            <select value={selectedOpponent} onChange={e => { setSelectedOpponent(e.target.value); setResult(null); }} style={{ minWidth: 200 }}>
              {opponents.map(t => <option key={t.id} value={t.id}>{t.name}</option>)}
            </select>
            <button className="btn btn-primary btn-lg" onClick={handleGenerate} disabled={loading || !selectedOpponent}>
              {loading ? <><span className="loading-spinner"></span> Running Pipeline...</> : '♟️ Generate Game Plan'}
            </button>
          </div>
        </div>
        
        {(loading || result) && (
          <div style={{ marginTop: 12 }}>
            <AgentPipeline activeStep={loading ? 1 : 4} completed={!!result && !loading} />
          </div>
        )}
      </div>

      <div className="page-content">
        {!result && !loading && (
          <div style={{ textAlign: 'center', padding: '64px' }}>
            <div style={{ fontSize: '64px', marginBottom: 16 }}>♟️</div>
            <div style={{ fontWeight: 700, fontSize: '20px', marginBottom: 8 }}>Generate Your Game Plan</div>
            <div style={{ color: 'var(--text-muted)', marginBottom: 8 }}>
              {team?.name} vs {opponent?.name}
            </div>
            <div style={{ color: 'var(--text-muted)', fontSize: '13px', maxWidth: 500, margin: '0 auto 32px' }}>
              The AI pipeline will run all 4 agents: Match Analysis → Opponent Scout → Strategy → Coaching Instructions
            </div>
            <button className="btn btn-primary btn-lg" onClick={handleGenerate} disabled={loading}>
              ♟️ Generate Full Game Plan
            </button>
          </div>
        )}

        {loading && (
          <div style={{ textAlign: 'center', padding: '64px' }}>
            <div style={{ marginBottom: 24 }}>
              <span className="loading-spinner" style={{ width: 48, height: 48, borderWidth: 4 }}></span>
            </div>
            <div style={{ fontWeight: 600, fontSize: '16px', marginBottom: 8 }}>AI Agents Running...</div>
            <div style={{ color: 'var(--text-muted)', fontSize: '13px' }}>
              Analyzing {opponent?.name}'s patterns and generating optimal strategy
            </div>
          </div>
        )}

        {result && rec && (
          <>
            {/* AI Info banner */}
            <div className="ai-banner" style={{ marginBottom: 24 }}>
              🤖 Strategy generated by {result.aiBackend} · {result.agents?.strategyRecommendation?.supportingEvidence?.length || 0} RAG documents used
              {!result.graniteConnected && <span style={{ color: 'var(--warning)', marginLeft: 12 }}>⚠️ {result.note?.slice(0, 80)}...</span>}
            </div>

            {/* Tabs */}
            <div style={{ display: 'flex', gap: 4, marginBottom: 24, overflowX: 'auto', paddingBottom: 4 }}>
              {tabs.map(tab => (
                <button
                  key={tab}
                  onClick={() => setActiveTab(tab)}
                  className="btn"
                  style={{
                    background: activeTab === tab ? 'var(--accent)' : 'var(--bg-secondary)',
                    color: activeTab === tab ? 'white' : 'var(--text-secondary)',
                    border: `1px solid ${activeTab === tab ? 'var(--accent)' : 'var(--border)'}`,
                    padding: '8px 16px', fontSize: '13px', whiteSpace: 'nowrap'
                  }}
                >
                  {tab.charAt(0).toUpperCase() + tab.slice(1)}
                </button>
              ))}
            </div>

            {/* Overview Tab */}
            {activeTab === 'overview' && (
              <div>
                <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr 1fr', gap: 24, marginBottom: 24 }}>
                  {/* Recommended formation */}
                  <Section title="Recommended Formation" icon="📐">
                    <div style={{ textAlign: 'center', marginBottom: 12 }}>
                      <span style={{ fontSize: '24px', fontWeight: 900, color: 'var(--accent)' }}>{rec.formation}</span>
                    </div>
                    {formations && rec.formation && formations[rec.formation] && (
                      <FormationPitch formation={formations[rec.formation]} teamColor={team?.color || '#3b82f6'} size="sm" />
                    )}
                  </Section>

                  {/* Alternative formation */}
                  <Section title="Alternative Formation" icon="🔄">
                    <div style={{ textAlign: 'center', marginBottom: 12 }}>
                      <span style={{ fontSize: '24px', fontWeight: 900, color: 'var(--text-secondary)' }}>{rec.alternativeFormation}</span>
                    </div>
                    {formations && rec.alternativeFormation && formations[rec.alternativeFormation] && (
                      <FormationPitch formation={formations[rec.alternativeFormation]} teamColor={team?.color || '#3b82f640'} size="sm" />
                    )}
                    <div style={{ fontSize: '11px', color: 'var(--text-muted)', textAlign: 'center', marginTop: 8 }}>Use if game state changes</div>
                  </Section>

                  {/* Quick summary */}
                  <Section title="Game Plan Summary" icon="📋">
                    {summary && (
                      <>
                        <InfoTag label="Formation" value={summary.recommendedFormation} color="var(--accent)" />
                        <InfoTag label="Top Attack Priority" value={summary.topAttackingPriority?.slice(0, 40) || '-'} color="var(--warning)" />
                        <InfoTag label="Top Defense Priority" value={summary.topDefensivePriority?.slice(0, 40) || '-'} color="var(--info)" />
                        <InfoTag label="Key Weakness" value={summary.keyWeaknessToExploit || '-'} color="var(--danger)" />
                        <div style={{ marginTop: 12 }}>
                          <ConfidenceBar value={summary.overallConfidence || 0.85} label="Overall AI Confidence" />
                        </div>
                      </>
                    )}
                  </Section>
                </div>

                {/* Strategy text */}
                <Section title="AI Strategy Summary" icon="🤖" style={{ marginBottom: 24 }}>
                  <div style={{ background: 'var(--bg-secondary)', padding: 16, borderRadius: 8, borderLeft: '3px solid var(--accent)' }}>
                    <p style={{ margin: 0, fontSize: '13px', color: 'var(--text-secondary)', lineHeight: 1.7 }}>{rec.summary}</p>
                  </div>
                </Section>

                {/* Key principles */}
                {result.agents?.strategyRecommendation?.keyPrinciples?.length > 0 && (
                  <Section title="Key Tactical Principles" icon="💡">
                    {result.agents.strategyRecommendation.keyPrinciples.map((p, i) => (
                      <div key={i} style={{ display: 'flex', gap: 10, padding: '10px 0', borderBottom: '1px solid var(--border)' }}>
                        <span style={{ color: 'var(--accent)', fontWeight: 700 }}>{i+1}.</span>
                        <span style={{ fontSize: '13px', color: 'var(--text-secondary)' }}>{p}</span>
                      </div>
                    ))}
                  </Section>
                )}
              </div>
            )}

            {/* Attacking Tab */}
            {activeTab === 'attacking' && (
              <div>
                <Section title="Attacking Strategy" icon="⚔️" style={{ marginBottom: 24 }}>
                  <div style={{ marginBottom: 16 }}>
                    <span className="badge badge-warning" style={{ marginRight: 8 }}>Style: {rec.attacking?.style}</span>
                    <span className="badge badge-info">Build-up: {rec.attacking?.buildUp?.replace(/_/g, ' ')}</span>
                  </div>
                  {rec.attacking?.priorities?.map((p, i) => (
                    <div key={i} style={{ padding: '14px 16px', borderRadius: 8, marginBottom: 10, background: 'var(--bg-secondary)', borderLeft: `3px solid var(--warning)` }}>
                      <div style={{ display: 'flex', alignItems: 'center', gap: 8, marginBottom: 6 }}>
                        <span style={{ background: 'var(--warning)', color: 'white', borderRadius: '50%', width: 22, height: 22, display: 'flex', alignItems: 'center', justifyContent: 'center', fontSize: 11, fontWeight: 700 }}>{p.priority}</span>
                        <span style={{ fontWeight: 600, fontSize: '14px' }}>{p.instruction}</span>
                      </div>
                      <p style={{ margin: 0, fontSize: '12px', color: 'var(--text-muted)', paddingLeft: 30 }}>{p.detail}</p>
                    </div>
                  ))}
                </Section>

                <Section title="Set Pieces - Attack" icon="🎯">
                  <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: 16 }}>
                    <div>
                      <div style={{ fontWeight: 600, marginBottom: 8 }}>Corners</div>
                      <p style={{ fontSize: '13px', color: 'var(--text-secondary)' }}>{rec.setpieces?.attacking?.corners}</p>
                    </div>
                    <div>
                      <div style={{ fontWeight: 600, marginBottom: 8 }}>Free Kicks</div>
                      <p style={{ fontSize: '13px', color: 'var(--text-secondary)' }}>{rec.setpieces?.attacking?.freekicks}</p>
                      <div style={{ fontSize: 12, color: 'var(--text-muted)' }}>Set piece taker: {rec.setpieces?.attacking?.keyTaker}</div>
                    </div>
                  </div>
                </Section>
              </div>
            )}

            {/* Defending Tab */}
            {activeTab === 'defending' && (
              <div>
                <Section title="Defensive Setup" icon="🏰" style={{ marginBottom: 24 }}>
                  <div style={{ marginBottom: 16, display: 'flex', gap: 8, flexWrap: 'wrap' }}>
                    <span className="badge badge-info">Structure: {rec.defending?.structure?.replace(/_/g, ' ')}</span>
                    <span className="badge badge-muted">Line: {rec.defending?.lineHeight}</span>
                    <span className="badge badge-muted">Press: {rec.defending?.pressingIntensity}</span>
                  </div>
                  {rec.defending?.priorities?.map((p, i) => (
                    <div key={i} style={{ padding: '14px 16px', borderRadius: 8, marginBottom: 10, background: 'var(--bg-secondary)', borderLeft: '3px solid var(--info)' }}>
                      <div style={{ display: 'flex', alignItems: 'center', gap: 8, marginBottom: 6 }}>
                        <span style={{ background: 'var(--info)', color: 'white', borderRadius: '50%', width: 22, height: 22, display: 'flex', alignItems: 'center', justifyContent: 'center', fontSize: 11, fontWeight: 700 }}>{p.priority}</span>
                        <span style={{ fontWeight: 600 }}>{p.instruction}</span>
                      </div>
                      <p style={{ margin: 0, fontSize: '12px', color: 'var(--text-muted)', paddingLeft: 30 }}>{p.detail}</p>
                    </div>
                  ))}
                </Section>

                <Section title="Pressing System" icon="⚡" style={{ marginBottom: 24 }}>
                  <div style={{ marginBottom: 12 }}>
                    <span className="badge badge-accent">Intensity: {rec.pressing?.intensity}</span>
                  </div>
                  <div style={{ marginBottom: 12 }}>
                    <div style={{ fontWeight: 600, marginBottom: 8 }}>Press Triggers</div>
                    <div style={{ display: 'flex', flexWrap: 'wrap', gap: 6 }}>
                      {rec.pressing?.trigger?.map((t, i) => <span key={i} className="badge badge-warning">{t.replace(/_/g, ' ')}</span>)}
                    </div>
                  </div>
                  <p style={{ fontSize: 13, color: 'var(--text-secondary)' }}>{rec.pressing?.description}</p>
                </Section>

                <Section title="Transition Plan" icon="🔄">
                  <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: 16 }}>
                    <div>
                      <div style={{ fontWeight: 600, marginBottom: 8, color: 'var(--success)' }}>Winning Transition</div>
                      <p style={{ fontSize: '13px', color: 'var(--text-secondary)' }}>{rec.transitions?.attacking}</p>
                    </div>
                    <div>
                      <div style={{ fontWeight: 600, marginBottom: 8, color: 'var(--danger)' }}>Defensive Transition</div>
                      <p style={{ fontSize: '13px', color: 'var(--text-secondary)' }}>{rec.transitions?.defending}</p>
                    </div>
                  </div>
                  <div style={{ padding: '12px', background: 'var(--bg-secondary)', borderRadius: 8, marginTop: 12, borderLeft: '3px solid var(--accent)', fontSize: 13, color: 'var(--text-secondary)' }}>
                    <strong>Focus: </strong>{rec.transitions?.focus}
                  </div>
                </Section>
              </div>
            )}

            {/* Players Tab */}
            {activeTab === 'players' && rec.playerInstructions?.length > 0 && (
              <Section title="Individual Player Instructions" icon="👤">
                {rec.playerInstructions.map((pi, i) => (
                  <div key={i} style={{
                    padding: '12px 16px', borderRadius: 8, marginBottom: 8, background: 'var(--bg-secondary)',
                    borderLeft: `3px solid ${pi.isKeyPlayer ? 'var(--success)' : 'var(--border-light)'}`
                  }}>
                    <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: 6 }}>
                      <div style={{ fontWeight: 600 }}>{pi.player} <span className="badge badge-muted">{pi.position}</span></div>
                      {pi.isKeyPlayer && <span className="badge badge-success">Key Player</span>}
                    </div>
                    <p style={{ margin: 0, fontSize: '13px', color: 'var(--text-secondary)' }}>{pi.instruction}</p>
                  </div>
                ))}
              </Section>
            )}

            {/* Alternatives Tab */}
            {activeTab === 'alternatives' && (
              <div>
                <Section title="Situational Alternative Plans" icon="🔄" style={{ marginBottom: 24 }}>
                  {result.agents?.strategyRecommendation?.alternativePlans?.map((plan, i) => (
                    <div key={i} style={{ padding: '16px', borderRadius: 8, marginBottom: 12, background: 'var(--bg-secondary)', border: '1px solid var(--border)' }}>
                      <div style={{ display: 'flex', justifyContent: 'space-between', marginBottom: 8 }}>
                        <div style={{ fontWeight: 600 }}>{plan.scenario}</div>
                        <span className="badge badge-accent">{plan.formation}</span>
                      </div>
                      <p style={{ margin: 0, fontSize: '13px', color: 'var(--text-secondary)' }}>{plan.description}</p>
                    </div>
                  ))}
                </Section>

                <Section title="In-Game Tactical Adjustments" icon="⚡">
                  {result.agents?.strategyRecommendation?.inGameAdjustments?.map((adj, i) => (
                    <div key={i} style={{ display: 'flex', gap: 12, padding: '10px 0', borderBottom: '1px solid var(--border)', fontSize: 13 }}>
                      <div style={{ color: 'var(--warning)', fontWeight: 600, minWidth: 220 }}>{adj.trigger}</div>
                      <div style={{ color: 'var(--text-secondary)' }}>{adj.action}</div>
                    </div>
                  ))}
                </Section>
              </div>
            )}

            {/* Coaching Tab */}
            {activeTab === 'coaching' && explanation && (
              <div>
                <Section title="Pre-Match Team Briefing" icon="📢" style={{ marginBottom: 24 }}>
                  <div style={{ background: 'linear-gradient(135deg, rgba(59,130,246,0.1), rgba(139,92,246,0.1))', border: '1px solid rgba(59,130,246,0.3)', borderRadius: 12, padding: 20, marginBottom: 16 }}>
                    <p style={{ margin: 0, fontSize: '15px', fontWeight: 500, color: 'var(--text-primary)', fontStyle: 'italic', lineHeight: 1.7 }}>
                      "{explanation.briefing?.openingStatement}"
                    </p>
                  </div>
                  <InfoTag label="Formation Rationale" value={explanation.briefing?.formationRationale?.slice(0, 80) + '...'} />
                  <InfoTag label="Primary Objective" value={explanation.briefing?.primaryObjective} color="var(--warning)" />
                </Section>

                <Section title="Pre-Game Checklist" icon="✅" style={{ marginBottom: 24 }}>
                  {explanation.pregameChecklist?.map((item, i) => (
                    <div key={i} style={{ padding: '8px 0', borderBottom: '1px solid var(--border)', fontSize: 13, color: 'var(--text-secondary)' }}>{item}</div>
                  ))}
                </Section>

                <Section title="Half-Time Scenarios" icon="⏱️" style={{ marginBottom: 24 }}>
                  {explanation.halftimeAdjustments?.map((adj, i) => (
                    <div key={i} style={{ padding: '14px', borderRadius: 8, marginBottom: 10, background: 'var(--bg-secondary)', borderLeft: '3px solid var(--accent)' }}>
                      <div style={{ fontWeight: 600, marginBottom: 6, color: 'var(--accent)' }}>{adj.scenario}</div>
                      <p style={{ margin: 0, fontSize: 13, color: 'var(--text-secondary)' }}>{adj.instruction}</p>
                    </div>
                  ))}
                </Section>

                <Section title="Coaching Keywords" icon="🔑">
                  <div style={{ display: 'flex', flexWrap: 'wrap', gap: 8 }}>
                    {explanation.tacticalKeywords?.map((kw, i) => (
                      <span key={i} className="badge badge-accent">{kw}</span>
                    ))}
                  </div>
                  <div style={{ marginTop: 16, background: 'var(--bg-secondary)', borderRadius: 8, padding: 16 }}>
                    <div style={{ fontWeight: 600, marginBottom: 8, fontSize: 13 }}>AI Explanation</div>
                    <p style={{ margin: 0, fontSize: 13, color: 'var(--text-secondary)', lineHeight: 1.7 }}>{explanation.explanation?.text}</p>
                    <div style={{ marginTop: 12 }}>
                      <ConfidenceBar value={explanation.explanation?.confidence || 0.85} />
                    </div>
                  </div>
                </Section>
              </div>
            )}
          </>
        )}
      </div>
    </div>
  );
}
